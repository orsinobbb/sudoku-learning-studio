import { writeFile } from 'node:fs/promises';
import { TECHNIQUE_RANKS, analyzePuzzle, countSolutions, generateSolution, parsePuzzle, serializeGrid, solveGrid, transformPuzzle } from '../src/core/sudoku.js';

const blankTargets = Array.from({ length: 30 }, (_, index) => index + 35);
const rankBands = [[1, 1], [2, 2], [3, 5], [6, 8], [9, 14]];

function randomFor(seed) {
  let value = 2166136261;
  for (const character of seed) value = Math.imul(value ^ character.charCodeAt(0), 16777619);
  return () => {
    value += 0x6D2B79F5;
    let output = value;
    output = Math.imul(output ^ (output >>> 15), output | 1);
    output ^= output + Math.imul(output ^ (output >>> 7), output | 61);
    return ((output ^ (output >>> 14)) >>> 0) / 4294967296;
  };
}

function shuffle(values, random) {
  const output = [...values];
  for (let index = output.length - 1; index > 0; index -= 1) {
    const swap = Math.floor(random() * (index + 1));
    [output[index], output[swap]] = [output[swap], output[index]];
  }
  return output;
}

function randomPuzzle(seed, targetBlanks) {
  const puzzle = generateSolution(`${seed}:solution`);
  const order = shuffle(Array.from({ length: 81 }, (_, index) => index), randomFor(`${seed}:remove`));
  let blanks = 0;
  for (const index of order) {
    if (blanks >= targetBlanks) break;
    const value = puzzle[index];
    puzzle[index] = 0;
    if (countSolutions(puzzle, 2) === 1) blanks += 1;
    else puzzle[index] = value;
  }
  return blanks === targetBlanks ? puzzle : null;
}

function hardest(report) {
  return report.steps.reduce((result, step) => TECHNIQUE_RANKS[step.strategy] > TECHNIQUE_RANKS[result] ? step.strategy : result, 'fullHouse');
}

function validateCandidate(puzzle, minRank, maxRank) {
  const report = analyzePuzzle(puzzle);
  const technique = hardest(report);
  const rank = TECHNIQUE_RANKS[technique];
  return report.unique && rank >= minRank && rank <= maxRank ? technique : null;
}

async function hardSources() {
  const response = await fetch('https://norvig.com/top95.txt');
  if (!response.ok) throw new Error(`Cannot fetch top95: ${response.status}`);
  return (await response.text()).trim().split(/\r?\n/).map(parsePuzzle);
}

function addSolutionClues(source, targetBlanks, seed) {
  const solution = solveGrid(source);
  if (!solution) return null;
  const puzzle = [...source];
  let blanks = puzzle.filter((value) => !value).length;
  if (blanks < targetBlanks) return null;
  for (const index of shuffle(puzzle.map((value, index) => value ? -1 : index).filter((index) => index >= 0), randomFor(seed))) {
    if (blanks <= targetBlanks) break;
    puzzle[index] = solution[index];
    blanks -= 1;
  }
  return blanks === targetBlanks ? puzzle : null;
}

const hard = await hardSources();
const output = [];
const seenPuzzles = new Set();
for (let index = 0; index < blankTargets.length; index += 1) {
  const level = index + 1;
  const stage = Math.floor(index / 6);
  const blanks = blankTargets[index];
  const [minRank, maxRank] = stage === 4
    ? (level === 30 ? [14, 14] : [9, 13])
    : rankBands[stage];
  let focusTechnique = null;
  const puzzles = [];
  for (let question = 1; question <= 10; question += 1) {
    let match = null;
    for (let attempt = 0; attempt < 12000 && !match; attempt += 1) {
      const useHardSource = stage >= 3 && attempt % 2 === 1;
      const sourceIndex = (level * 97 + question * 53 + attempt * 31) % hard.length;
      const seed = `${level}-${question}-${attempt}`;
      const candidate = useHardSource
        ? addSolutionClues(transformPuzzle(hard[sourceIndex], `source-${seed}`), blanks, `add-${seed}`)
        : randomPuzzle(`bank-${seed}`, blanks);
      if (!candidate) continue;
      const serialized = serializeGrid(candidate);
      if (seenPuzzles.has(serialized)) continue;
      const technique = validateCandidate(candidate, minRank, maxRank);
      if (!technique || (focusTechnique && technique !== focusTechnique)) continue;
      match = { puzzle: serialized, hardestTechnique: technique, source: useHardSource ? 'norvig-top95' : 'generated' };
    }
    if (!match) throw new Error(`No candidate for level ${level}, question ${question}`);
    focusTechnique ||= match.hardestTechnique;
    seenPuzzles.add(match.puzzle);
    puzzles.push(match);
  }
  output.push({ level, blanks, minRank, maxRank, hardestTechniques: [focusTechnique], puzzles });
  console.log(`L${String(level).padStart(2, '0')} blanks=${blanks} technique=${focusTechnique}`);
}

const banner = '// Generated by tools/build-level-bank.mjs. Do not edit by hand.\n';
await writeFile(new URL('../src/learning/level-puzzles.generated.js', import.meta.url), `${banner}export const LEVEL_PUZZLE_BASES = ${JSON.stringify(output, null, 2)};\n`, 'utf8');
