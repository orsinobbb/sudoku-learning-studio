import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { logicalSolve, parsePuzzle } from '../src/core/sudoku.js';
import { LEVEL_PUZZLE_BASES } from '../src/learning/level-puzzles.generated.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourceByTechnique = new Map();

for (const level of LEVEL_PUZZLE_BASES) {
  for (const [questionIndex, record] of level.puzzles.entries()) {
    const trace = logicalSolve(parsePuzzle(record.puzzle), {
      includeSnapshots: true,
      allowSearch: true,
      allowUniqueness: true,
      allowAdvanced: true
    });
    const techniques = new Set(trace.steps.filter((step) => step.snapshot).map((step) => step.strategy));
    for (const technique of techniques) {
      const sources = sourceByTechnique.get(technique) || [];
      if (sources.length >= 12) continue;
      sources.push(Object.freeze({
        id: `L${String(level.level).padStart(2, '0')}-Q${String(questionIndex + 1).padStart(2, '0')}`,
        puzzle: record.puzzle
      }));
      sourceByTechnique.set(technique, sources);
    }
  }
}

const ordered = Object.fromEntries([...sourceByTechnique.entries()]
  .sort(([left], [right]) => left.localeCompare(right)));
const output = `// Generated by tools/build-assessment-sources.mjs. Do not edit by hand.\nexport const ASSESSMENT_SOURCES = Object.freeze(${JSON.stringify(ordered, null, 2)});\n`;
await writeFile(resolve(root, 'src/learning/assessment-sources.generated.js'), output, 'utf8');
console.log(`Generated assessment sources for ${Object.keys(ordered).length} techniques.`);
